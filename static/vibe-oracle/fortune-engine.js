export function selectFortune(history = [], random = Math.random) {
  const knownIds = new Set(FORTUNES.map((fortune) => fortune.id));
  const cleanHistory = history.filter((id) => knownIds.has(id));
  let candidates = FORTUNES.filter((fortune) => !cleanHistory.includes(fortune.id));

  if (!candidates.length) {
    const lastId = cleanHistory.at(-1);
    candidates = FORTUNES.filter((fortune) => fortune.id !== lastId);
  }

  const fortune = candidates[Math.floor(random() * candidates.length)] || FORTUNES[0];
  const nextHistory = [...cleanHistory.filter((id) => id !== fortune.id), fortune.id]
    .slice(-FORTUNES.length);
  return { fortune, history: nextHistory };
}
